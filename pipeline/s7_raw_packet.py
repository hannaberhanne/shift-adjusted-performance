#!/usr/bin/env python3
"""Stage 7: bundle the evidence and analysis tables into one workbook for the reviewer.

Inputs:   the stage 2 and stage 4 CSVs in output/
Outputs:  output/performance_raw_packet.xlsx
"""

from __future__ import annotations

import csv
import sys
from pathlib import Path

from openpyxl import Workbook
from openpyxl.styles import Font
from openpyxl.utils import get_column_letter

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import OUT  # noqa: E402

OUT_XLSX = OUT / "performance_raw_packet.xlsx"

CSV_SHEETS = [
    ("evidence_activity_enriched.csv", "raw_activity"),
    ("evidence_incident_summary.csv", "incident_summary"),
    ("evidence_shift_slots.csv", "shift_slots"),
    ("evidence_student_time_context.csv", "student_time_ctx"),
    ("evidence_pair_overlap_slots.csv", "pair_overlap"),
    ("performance_student_analysis.csv", "perf_student"),
    ("performance_metric_distribution.csv", "perf_metric_dist"),
    ("performance_pairing_actor_view.csv", "perf_pair_actor"),
    ("performance_shift_window_analysis.csv", "perf_shift_window"),
]


def write_csv_to_sheet(wb: Workbook, csv_path: Path, sheet_name: str) -> None:
    ws = wb.create_sheet(title=sheet_name[:31])
    with csv_path.open(newline="", encoding="utf-8-sig") as fh:
        rows = list(csv.reader(fh))
    for row in rows:
        ws.append(row)

    if not rows:
        return

    # Style header.
    for cell in ws[1]:
        cell.font = Font(bold=True)
    ws.freeze_panes = "A2"
    ws.auto_filter.ref = ws.dimensions

    # Width cap keeps workbook usable in Excel.
    max_cols = len(rows[0])
    for c in range(1, max_cols + 1):
        col_letter = get_column_letter(c)
        values = [str(ws.cell(row=r, column=c).value or "") for r in range(1, min(ws.max_row, 200) + 1)]
        width = min(60, max(10, max(len(v) for v in values) + 2))
        ws.column_dimensions[col_letter].width = width


def write_readme_sheet(wb: Workbook) -> None:
    ws = wb.active
    ws.title = "README"
    lines = [
        "Performance Raw Packet",
        "",
        "Purpose:",
        "Raw mined evidence + standardized performance analysis for scorecard normalization.",
        "",
        "Sheet guide:",
        "1) raw_activity: event-level mined records with weekend/night/slow/co-scheduling context.",
        "2) incident_summary: incident span/timeline metrics and slow-ticket flags.",
        "3) shift_slots: schedule slots with staff composition (weekend/night flags).",
        "4) student_time_ctx: student context counts (weekend/night/slow/on-slot).",
        "5) pair_overlap: schedule-level co-scheduling overlap counts.",
        "6) perf_student: standardized student performance table (z-scores + ranks).",
        "7) perf_metric_dist: normalization baselines (mean/std/quantiles by metric).",
        "8) perf_pair_actor: actor-view performance while co-scheduled with each peer.",
        "9) perf_shift_window: performance by day type and shift window.",
        "",
        "Standardization:",
        "- Z-scores use Coverage == Full students only.",
        "- Lower-is-better metrics are inverted in z-space.",
        "- ContextAdjustedPerformanceZ = CorePerformanceZ + ContextLoadZ.",
        "",
        "Generated by pipeline/s7_raw_packet.py from the output/ folder.",
    ]
    for line in lines:
        ws.append([line])
    ws["A1"].font = Font(bold=True)
    ws.column_dimensions["A"].width = 120


def main() -> None:
    wb = Workbook()
    write_readme_sheet(wb)

    for csv_name, sheet_name in CSV_SHEETS:
        p = OUT / csv_name
        if p.exists():
            write_csv_to_sheet(wb, p, sheet_name)

    wb.save(OUT_XLSX)
    print(f"Wrote {OUT_XLSX.name}")


if __name__ == "__main__":
    main()
